/**
 * Queue Newsletter Script
 *
 * Scans recent song masterclasses and content updates, queuing them up
 * into a pending newsletter digest (JSON and Markdown) for scheduled publication.
 *
 * Usage:
 *   npx tsx scripts/queue-newsletter.ts [--limit 5]
 */

import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(__dirname, '..');
const SONGS_DIR = path.join(ROOT, 'src/data/songs');
const NEWSLETTER_DATA = path.join(ROOT, 'src/data/newsletter/pending-digest.json');
const NEWSLETTER_DOC = path.join(ROOT, 'docs/newsletter/pending-digest.md');

interface SongData {
  songInfo: {
    title: string;
    artist: string;
    key: string;
    tempo: string;
  };
  difficulty?: {
    overall: string;
  };
  musicalAnalysis?: {
    chordProgressions?: {
      mainProgression?: {
        description?: string;
      };
    };
  };
  metadata?: {
    dateAdded?: string;
  };
}

function getRecentSongs(limit = 5) {
  const files = fs.readdirSync(SONGS_DIR).filter(f => f.endsWith('.json') && !f.startsWith('_'));
  const songs: Array<{ slug: string; data: SongData }> = [];

  for (const file of files) {
    const slug = file.replace('.json', '');
    const data: SongData = JSON.parse(fs.readFileSync(path.join(SONGS_DIR, file), 'utf8'));
    songs.push({ slug, data });
  }

  // Sort descending by dateAdded
  songs.sort((a, b) => {
    const dateA = new Date(a.data.metadata?.dateAdded || '2024-01-01').getTime();
    const dateB = new Date(b.data.metadata?.dateAdded || '2024-01-01').getTime();
    return dateB - dateA;
  });

  return songs.slice(0, limit);
}

function run() {
  console.log('Queuing latest masterclass updates for scheduled newsletter release...\n');
  const recent = getRecentSongs(5);

  const queuedSongs = recent.map(({ slug, data }) => ({
    title: data.songInfo.title,
    artist: data.songInfo.artist,
    slug,
    key: data.songInfo.key,
    tempo: data.songInfo.tempo,
    difficulty: data.difficulty?.overall || 'Intermediate',
    theoryTakeaway: data.musicalAnalysis?.chordProgressions?.mainProgression?.description || 'Deep harmonic and technique breakdown.',
    link: `https://musicscene.com.au/lessons/songs/song-analysis/${slug}`
  }));

  const digestData = {
    queueStatus: 'pending_publication',
    scheduledCadence: 'weekly',
    name: 'The MusicScene Digest',
    tagline: 'Weekly Guitar Masterclasses, Theory Secrets & Tone Stack Dials',
    lastQueuedAt: new Date().toISOString(),
    queuedSongCount: queuedSongs.length,
    queuedSongs
  };

  // Ensure output directory exists
  fs.mkdirSync(path.dirname(NEWSLETTER_DATA), { recursive: true });
  fs.writeFileSync(NEWSLETTER_DATA, JSON.stringify(digestData, null, 2) + '\n', 'utf8');

  // Build markdown draft
  fs.mkdirSync(path.dirname(NEWSLETTER_DOC), { recursive: true });
  const mdContent = `# The MusicScene Digest — Pending Scheduled Edition
**Weekly Guitar Masterclasses, Theory Secrets & Tone Stack Dials**

* **Status:** Queued for next scheduled dispatch
* **Queued Changes:** ${queuedSongs.length} song masterclasses

---

Hey guitarist,

Here is your scheduled MusicScene digest, gathering all the masterclasses and theory insights queued up in the practice room this week:

## 🎸 Queued Masterclasses
${queuedSongs.map((s, i) => `
### ${i + 1}. ${s.title} — ${s.artist}
* **Key & Tempo:** ${s.key} • ${s.tempo}
* **Difficulty:** ${s.difficulty}
* **Harmonic Breakdown:** ${s.theoryTakeaway}
* **Masterclass Link:** [Practice ${s.title}](${s.link})
`).join('')}

---
*Generated by \`scripts/queue-newsletter.ts\` for scheduled publication.*
`;

  fs.writeFileSync(NEWSLETTER_DOC, mdContent, 'utf8');

  console.log(`Successfully queued ${queuedSongs.length} songs:`);
  queuedSongs.forEach(s => console.log(`  - ${s.title} by ${s.artist} (${s.slug})`));
  console.log(`\nSaved data to: ${NEWSLETTER_DATA}`);
  console.log(`Saved draft to: ${NEWSLETTER_DOC}`);
}

run();

